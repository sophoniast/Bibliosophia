export const DEFAULT_THEME = 'abbey'
export const DEFAULT_MODE = 'night'

function createTheme({ id, name, description, heading, body, tech, day, night }) {
  return {
    id,
    name,
    description,
    fonts: {
      heading,
      body,
      tech,
      display: heading,
      serif: heading,
      sans: body,
      mono: tech,
    },
    day: createPalette(day),
    night: createPalette(night),
  }
}

function createPalette({ bg, text, accent }) {
  return {
    bg,
    surface: bg,
    surfaceAlt: bg,
    text,
    textMuted: text,
    accent,
  }
}
