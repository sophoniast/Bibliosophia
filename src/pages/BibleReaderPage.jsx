    greek: entry.greek || original.greek || (isGreek ? entry.lemma : ''),
    greekTranslit: entry.greekTranslit || original.greekTranslit || (isGreek ? entry.translit : ''),
    hebrew: entry.hebrew || original.hebrew || (isHebrew ? entry.lemma : ''),
